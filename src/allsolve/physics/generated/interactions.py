class MeshDeformationPeriodicity(Interaction):
    """Periodicity interaction."""

    definition_id = "meshDeformationPeriodicity"
    physics_definition_id = "meshDeformation"
    target_definition_ids = {
        "target_1": "meshDeformationPeriodicityTarget1",
        "target_2": "meshDeformationPeriodicityTarget2",
    }

    def __init__(
        self,
        name: str,
        mesh_deformation_periodicity_anti_periodicity: BooleanValue,
        target_1: "Region | str",
        target_2: "Region | str",
        *,
        enabled: BooleanValue | None = None,
        mesh_deformation_periodicity_type: (
            MeshDeformationPeriodicityType | str
        ) = MeshDeformationPeriodicityType.TRANSLATION,
        mesh_deformation_periodicity_translation_direction: VectorValue | None = None,
        mesh_deformation_periodicity_translation_distance: ScalarValue | None = None,
        mesh_deformation_periodicity_rotation_center: VectorValue | None = None,
        mesh_deformation_periodicity_rotation_angle: VectorValue | None = None,
    ) -> None:
        """
        Create a periodicity interaction.

        Parameters:
            name: Name of the interaction.
            mesh_deformation_periodicity_anti_periodicity: Scales the field on target 2 by -1, so that the two boundaries are opposite instead of equal.
            target_1: Target region for target_1.
            target_2: Target region for target_2.
            enabled: Enabled state (bool or expression string). Defaults to enabled.
            mesh_deformation_periodicity_type: Whether target 2 is target 1 translated or target 1 rotated.
            mesh_deformation_periodicity_translation_direction: Direction target 1 is translated in to reach target 2. Only the direction matters, not the length.
            mesh_deformation_periodicity_translation_distance: Distance between target 1 and target 2 along the translation direction.
            mesh_deformation_periodicity_rotation_center: Point that the rotation from target 1 to target 2 turns around.
            mesh_deformation_periodicity_rotation_angle: Angle target 1 is rotated by around the center to reach target 2. In 3D one angle per axis, applied x then y then z.
        """
        _ebo_ctrl_0 = (
            mesh_deformation_periodicity_type.value
            if isinstance(mesh_deformation_periodicity_type, Enum)
            else mesh_deformation_periodicity_type
        )
        if _ebo_ctrl_0 == "meshDeformationPeriodicityTypeTranslation":
            if mesh_deformation_periodicity_translation_direction is None:
                raise ValueError(
                    "MeshDeformationPeriodicity: when mesh_deformation_periodicity_type selects option 'meshDeformationPeriodicityTypeTranslation', mesh_deformation_periodicity_translation_direction must not be None"
                )
        _ebo_ctrl_1 = (
            mesh_deformation_periodicity_type.value
            if isinstance(mesh_deformation_periodicity_type, Enum)
            else mesh_deformation_periodicity_type
        )
        if _ebo_ctrl_1 == "meshDeformationPeriodicityTypeTranslation":
            if mesh_deformation_periodicity_translation_distance is None:
                raise ValueError(
                    "MeshDeformationPeriodicity: when mesh_deformation_periodicity_type selects option 'meshDeformationPeriodicityTypeTranslation', mesh_deformation_periodicity_translation_distance must not be None"
                )
        _ebo_ctrl_2 = (
            mesh_deformation_periodicity_type.value
            if isinstance(mesh_deformation_periodicity_type, Enum)
            else mesh_deformation_periodicity_type
        )
        if _ebo_ctrl_2 == "meshDeformationPeriodicityTypeRotation":
            if mesh_deformation_periodicity_rotation_center is None:
                raise ValueError(
                    "MeshDeformationPeriodicity: when mesh_deformation_periodicity_type selects option 'meshDeformationPeriodicityTypeRotation', mesh_deformation_periodicity_rotation_center must not be None"
                )
        _ebo_ctrl_3 = (
            mesh_deformation_periodicity_type.value
            if isinstance(mesh_deformation_periodicity_type, Enum)
            else mesh_deformation_periodicity_type
        )
        if _ebo_ctrl_3 == "meshDeformationPeriodicityTypeRotation":
            if mesh_deformation_periodicity_rotation_angle is None:
                raise ValueError(
                    "MeshDeformationPeriodicity: when mesh_deformation_periodicity_type selects option 'meshDeformationPeriodicityTypeRotation', mesh_deformation_periodicity_rotation_angle must not be None"
                )
        parameters: List[InteractionParameter] = []
        parameters.append(
            InteractionParameter(
                definition="meshDeformationPeriodicityAntiPeriodicity",
                value=boolean_to_str(mesh_deformation_periodicity_anti_periodicity),
            )
        )
        parameters.append(
            InteractionParameter(
                definition="meshDeformationPeriodicityType",
                ascii_value=(
                    mesh_deformation_periodicity_type.value
                    if isinstance(mesh_deformation_periodicity_type, Enum)
                    else mesh_deformation_periodicity_type
                ),
            )
        )
        if mesh_deformation_periodicity_translation_direction is not None:
            parameters.append(
                InteractionParameter(
                    definition="meshDeformationPeriodicityTranslationDirection",
                    value=vector_to_str(
                        mesh_deformation_periodicity_translation_direction
                    ),
                )
            )
        if mesh_deformation_periodicity_translation_distance is not None:
            parameters.append(
                InteractionParameter(
                    definition="meshDeformationPeriodicityTranslationDistance",
                    value=str(mesh_deformation_periodicity_translation_distance),
                )
            )
        if mesh_deformation_periodicity_rotation_center is not None:
            parameters.append(
                InteractionParameter(
                    definition="meshDeformationPeriodicityRotationCenter",
                    value=vector_to_str(mesh_deformation_periodicity_rotation_center),
                )
            )
        if mesh_deformation_periodicity_rotation_angle is not None:
            parameters.append(
                InteractionParameter(
                    definition="meshDeformationPeriodicityRotationAngle",
                    value=vector_to_str(mesh_deformation_periodicity_rotation_angle),
                )
            )
        super().__init__(
            name=name,
            targets={"target_1": target_1, "target_2": target_2},
            enabled=enabled,
            parameters=parameters,
        )


